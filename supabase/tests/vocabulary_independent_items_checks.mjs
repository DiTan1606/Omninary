import fs from 'node:fs';
import assert from 'node:assert/strict';
export async function independentItemChecks({ db, migrationPath, user, other }) {
  const one = async (sql, args = []) => (await db.query(sql, args)).rows[0];
  const login = async (id) => db.exec(`RESET ROLE; SELECT set_config('request.jwt.claim.sub','${id}',false); SET ROLE authenticated;`);
  let checks = 0;
  const check = (value, label) => { assert.ok(value, label); checks++; };
  await db.exec('RESET ROLE');
  const before = (await db.query('SELECT * FROM user_vocabulary ORDER BY id')).rows;
  const contents = (await db.query("SELECT to_jsonb(v)-'word_id' item FROM vocab_catalog v ORDER BY id")).rows;
  const links = (await db.query("SELECT to_jsonb(m)-'display_group_id' item FROM user_topic_vocab m ORDER BY user_vocabulary_id,topic_id")).rows;
  await db.exec(fs.readFileSync(migrationPath, 'utf8'));
  assert.deepEqual((await db.query('SELECT * FROM user_vocabulary ORDER BY id')).rows, before); checks++;
  assert.deepEqual((await db.query('SELECT to_jsonb(v) item FROM vocab_catalog v ORDER BY id')).rows, contents); checks++;
  assert.deepEqual((await db.query('SELECT to_jsonb(m) item FROM user_topic_vocab m ORDER BY user_vocabulary_id,topic_id')).rows, links); checks++;
  check((await one("SELECT to_regclass('public.vocabulary_words') id")).id === null, 'spelling parent removed');
  check((await one("SELECT to_regclass('public.vocabulary_display_groups') id")).id === null, 'display groups removed');
  check((await one("SELECT to_regprocedure('public.group_vocabulary_meanings(uuid[],uuid,boolean)') id")).id === null, 'group operation removed');
  await login(user);
  const root = (await one('SELECT ensure_vocabulary_root() id')).id;
  const folder = (await one("INSERT INTO topics(name,visibility,owner_id) VALUES('Independent items test','private',$1) RETURNING id", [user])).id;
  const create = async (payload) => (await one('SELECT create_vocabulary_item($1,$2,false) id', [JSON.stringify(payload), root])).id;
  const a = await create({ word: 'read', ipa: '/riːd/', word_form: 'verb', v_meaning: 'đọc hiện tại', e_example: 'I read every day.' });
  const b = await create({ word: 'read', ipa: '/red/', word_form: 'verb', v_meaning: 'đã đọc', e_example: 'I read it yesterday.' });
  check(a !== b, 'same spelling produces independent catalog IDs');
  check((await one('SELECT count(*)::int n FROM user_vocabulary WHERE user_id=$1 AND vocab_id=ANY($2)',[user,[a,b]])).n === 2, 'new items each have progress');
  check((await one('SELECT count(*)::int n FROM user_vocabulary WHERE user_id=$1 AND vocab_id=ANY($2) AND learning_level=0',[user,[a,b]])).n === 2, 'new item starts at zero');
  await db.exec('RESET ROLE');
  await one('UPDATE user_vocabulary SET learning_level=4 WHERE user_id=$1 AND vocab_id=$2',[user,a]);
  await login(user);
  await one('SELECT save_vocabulary_to_topic($1,$2)',[[a,a],folder]);
  check((await one('SELECT count(*)::int n FROM user_vocabulary WHERE user_id=$1 AND vocab_id=$2',[user,a])).n === 1, 'one progress across collections');
  check((await one('SELECT learning_level FROM user_vocabulary WHERE user_id=$1 AND vocab_id=$2',[user,a])).learning_level === 4, 'adding existing item retains level');
  check((await one('SELECT learning_level FROM user_vocabulary WHERE user_id=$1 AND vocab_id=$2',[user,b])).learning_level === 0, 'same spelling other item retains own level');
  check((await one('SELECT ipa FROM vocab_catalog WHERE id=$1',[a])).ipa === '/riːd/', 'own pronunciation retained');
  check((await one('SELECT ipa FROM vocab_catalog WHERE id=$1',[b])).ipa === '/red/', 'different pronunciation retained');
  const snapshot = (await one("SELECT change_vocabulary_location($1,$2,$3,'move') snap",[[a],root,folder])).snap;
  check(snapshot.memberships.every(m => !('display_group_id' in m)), 'undo only captures memberships');
  await one('SELECT restore_vocabulary_locations($1)',[JSON.stringify(snapshot)]);
  check((await one('SELECT count(*)::int n FROM user_topic_vocab ut JOIN user_vocabulary uv ON uv.id=ut.user_vocabulary_id WHERE uv.user_id=$1 AND uv.vocab_id=$2',[user,a])).n === 2, 'undo restores both collections');
  await login(other);
  await assert.rejects(() => one("SELECT change_vocabulary_location($1,$2,$3,'add')",[[a],root,folder])); checks++;
  await login(user);
  await assert.rejects(() => create({word:'  '})); checks++;
  await db.exec('RESET ROLE');
  await db.exec(fs.readFileSync(migrationPath,'utf8'));
  check((await one('SELECT learning_level FROM user_vocabulary WHERE user_id=$1 AND vocab_id=$2',[user,a])).learning_level === 4, 'migration rerun preserves progress');
  console.log(`PASS: ${checks} independent vocabulary item checks`);
}
