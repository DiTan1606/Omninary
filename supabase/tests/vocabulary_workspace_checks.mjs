import assert from 'node:assert/strict';
import fs from 'node:fs';

export async function workspaceChecks({ db, migrationPath, user, other, meaning, secondMeaning, progress, systemTopic }) {
  let checks = 0;
  const one = async (sql, params = []) => (await db.query(sql, params)).rows[0];
  const check = (value, label) => { assert.ok(value, label); checks++; };
  const login = async (id) => {
    await db.exec('RESET ROLE');
    await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [id]);
    await db.exec('SET ROLE authenticated');
  };
  const change = (ids, source, dest, action) => one('SELECT change_vocabulary_location($1,$2,$3,$4) snap', [ids, source, dest, action]);
  const group = (ids, topic, ungroup = false) => one('SELECT group_vocabulary_meanings($1,$2,$3) snap', [ids, topic, ungroup]);
  const undo = (snapshot) => one('SELECT restore_vocabulary_locations($1)', [JSON.stringify(snapshot)]);
  const memberships = async () => (await one('SELECT count(*)::int n FROM user_topic_vocab WHERE user_vocabulary_id=$1', [progress])).n;
  const progressRow = () => one('SELECT * FROM user_vocabulary WHERE id=$1', [progress]);
  await db.exec('RESET ROLE');
  await db.exec(fs.readFileSync(migrationPath, 'utf8'));
  const before = await progressRow();
  await login(user);
  const root = (await one('SELECT ensure_vocabulary_root() id')).id;
  check((await one('SELECT ensure_vocabulary_root() id')).id === root, 'root is idempotent');
  check((await one('SELECT count(*)::int n FROM user_topic_vocab ut JOIN user_vocabulary uv ON uv.id=ut.user_vocabulary_id WHERE uv.vocab_id=$1 AND topic_id=$2', [secondMeaning, root])).n === 1, 'unfiled sense appears at root');
  check((await one('SELECT count(*)::int n FROM user_topic_vocab WHERE user_vocabulary_id=$1 AND topic_id=$2', [progress, root])).n === 0, 'filed sense is not automatically copied to root');
  await assert.rejects(() => one('DELETE FROM topics WHERE id=$1', [root])); checks++;
  const dest = (await one("INSERT INTO topics(name,visibility,owner_id) VALUES('Workspace test','private',$1) RETURNING id", [user])).id;
  const copySnapshot = (await change([meaning], systemTopic, dest, 'add')).snap;
  check(await memberships() === 2, 'add preserves source');
  await undo(copySnapshot);
  check(await memberships() === 1, 'undo restores memberships');
  await change([meaning], systemTopic, null, 'root');
  check((await one('SELECT count(*)::int n FROM user_topic_vocab WHERE user_vocabulary_id=$1 AND topic_id=$2', [progress, systemTopic])).n === 0, 'move to root removes source');
  await change([meaning], root, dest, 'move');
  check((await one('SELECT count(*)::int n FROM user_topic_vocab WHERE user_vocabulary_id=$1 AND topic_id=$2', [progress, root])).n === 0, 'move from root removes root entry');
  await change([meaning], dest, root, 'add');
  await change([meaning], dest, null, 'remove');
  check(await memberships() === 1, 'remove preserves remaining membership');
  const groupSnapshot = (await group([meaning, secondMeaning], root)).snap;
  const groups = async () => (await one('SELECT count(DISTINCT display_group_id)::int n FROM user_topic_vocab WHERE topic_id=$1 AND display_group_id IS NOT NULL', [root])).n;
  check(await groups() === 1, 'explicit group combines selected senses');
  await change([meaning], root, dest, 'add');
  check((await one('SELECT display_group_id FROM user_topic_vocab WHERE user_vocabulary_id=$1 AND topic_id=$2', [progress, dest])).display_group_id === null, 'grouping stays local to folder');
  const ungroupSnapshot = (await group([meaning, secondMeaning], root, true)).snap;
  check(await groups() === 0, 'ungroup only changes presentation');
  await undo(ungroupSnapshot);
  check(await groups() === 1, 'undo restores grouping');
  const unrelated = (await one('SELECT create_vocabulary_meaning($1,$2,false) id', [JSON.stringify({ word: 'book', v_meaning: 'sách' }), root])).id;
  await assert.rejects(() => group([meaning, unrelated], root)); checks++;
  await assert.rejects(() => group([meaning], root)); checks++;
  await login(other);
  check((await one('SELECT count(*)::int n FROM user_vocabulary_workspace')).n === 0, 'workspace belongs only to learner');
  check((await one('SELECT count(*)::int n FROM vocabulary_display_groups')).n === 0, 'grouping belongs only to learner');
  const otherRoot = (await one('SELECT ensure_vocabulary_root() id')).id;
  check(otherRoot !== root, 'learners have distinct root folders');
  await assert.rejects(() => change([meaning], root, otherRoot, 'add')); checks++;
  await assert.rejects(() => undo(groupSnapshot)); checks++;
  await login(user);
  await assert.rejects(() => change([meaning], root, otherRoot, 'move')); checks++;
  assert.deepEqual(await progressRow(), before); checks++;
  await one('DELETE FROM topics WHERE id=$1', [dest]);
  check((await one('SELECT count(*)::int n FROM user_vocabulary WHERE id=$1', [progress])).n === 1, 'folder deletion preserves progress');
  await one('SELECT delete_vocabulary_from_workspace($1)', [[unrelated]]);
  check((await one('SELECT count(*)::int n FROM user_vocabulary WHERE vocab_id=$1', [unrelated])).n === 0, 'global removal deletes own progress');
  check((await one('SELECT count(*)::int n FROM vocab_catalog WHERE id=$1', [unrelated])).n === 1, 'global removal retains reusable definitions');
  await db.exec('RESET ROLE');
  await db.exec(fs.readFileSync(migrationPath, 'utf8'));
  await login(user);
  check((await one('SELECT ensure_vocabulary_root() id')).id === root, 'migration rerun preserves root ID');
  assert.deepEqual(await progressRow(), before); checks++;
  console.log('PASS: ' + checks + ' vocabulary workspace checks');
  return checks;
}
